// Portable JSON is the source of truth. Generated CSS ships inside ui/**.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const source = "docs/ecosystem-v1/design-system/tokens.json";
const output = path.join(root, "ui/design-tokens.css");
const kebab = (value) => value.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
function generate(tokens) {
  const declarations = [];
  const add = (name, value) => declarations.push(`  --pl-${name}: ${value};`);
  const group = (prefix, values) =>
    Object.entries(values).forEach(([name, value]) =>
      add(`${prefix}-${kebab(name)}`, value),
    );
  group("color", tokens.color);
  add(
    "font-family",
    tokens.typography.family
      .map((v, i) =>
        i === tokens.typography.family.length - 1 ? v : JSON.stringify(v),
      )
      .join(", "),
  );
  for (const [name, value] of Object.entries(tokens.typography)) {
    if (name === "family") continue;
    for (const [property, n] of Object.entries(value)) {
      add(
        `type-${kebab(name)}-${kebab(property.replace(/Px$/, ""))}`,
        property.endsWith("Px") ? `${n}px` : n,
      );
    }
  }
  for (const [name, value] of Object.entries(tokens.layout))
    add(`layout-${kebab(name.replace(/Px$/, ""))}`, `${value}px`);
  for (const [name, value] of Object.entries(tokens.radius))
    add(`radius-${kebab(name.replace(/Px$/, ""))}`, `${value}px`);
  for (const [name, value] of Object.entries(tokens.spacing))
    add(kebab(name.replace(/Px$/, "")), `${value}px`);
  group("gradient", tokens.gradient);
  group("component", tokens.component);
  group("shadow", tokens.shadow);
  add("motion-button", `${tokens.motion.buttonMs}ms`);
  add("motion-legacy-breathe", `${tokens.motion.legacyBreatheSeconds}s`);
  // Flow Dock's specification values are intentionally not applied to Hub :root.
  return `/* Generated by node scripts/design-tokens.cjs from ${source}.\n * Edit the JSON, then regenerate; do not edit this file by hand. */\n:root {\n${declarations.join("\n")}\n}\n`;
}
if (require.main === module) {
  const css = generate(
    JSON.parse(fs.readFileSync(path.join(root, source), "utf8")),
  );
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== css) {
      console.error("Design token CSS is stale. Run npm run tokens:generate.");
      process.exitCode = 1;
    }
  } else fs.writeFileSync(output, css);
}
module.exports = { generate };
